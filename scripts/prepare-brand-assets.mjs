import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(resolve(root, 'apps/web/package.json'));
const sharp = require('sharp');
const tokens = JSON.parse(await readFile(resolve(root, 'brand/opfin.tokens.json'), 'utf8'));
const manifest = {
  brandSystemVersion: tokens.version,
  source: tokens.logo,
  appIcon: tokens.appIcon,
  fontSource: tokens.fontSource,
  files: {},
};
const digest = (data) => createHash('sha256').update(data).digest('hex');
const gitBlob = (data) => createHash('sha1').update(`blob ${data.length}\0`).update(data).digest('hex');

async function save(path, data) {
  const target = resolve(root, path);
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, data);
  manifest.files[path] = digest(data);
}

async function officialAsset(path, expectedBlob) {
  const response = await fetch(
    `https://raw.githubusercontent.com/rsms/inter/${tokens.fontSource.commit}/${path}`,
    { signal: AbortSignal.timeout(30000), redirect: 'error' },
  );
  if (!response.ok) throw new Error(`Official font source unavailable: ${response.status}`);
  const data = Buffer.from(await response.arrayBuffer());
  if (gitBlob(data) !== expectedBlob) throw new Error(`Official source integrity mismatch: ${path}`);
  return data;
}

function colouriseCurrentColour(svg, colour) {
  return Buffer.from(svg.toString('utf8').replaceAll('currentColor', colour));
}

const woff = await officialAsset('docs/font-files/InterVariable.woff2', '5a8d3e72ad7ffb62af3b146e1b1f54ab5813a212');
const ttf = await officialAsset('docs/font-files/InterVariable.ttf', '4ab79e0102bbe0ffa1ed879b13e52ac8c6487833');
const licence = await officialAsset('LICENSE.txt', '9b2ca37b3ffc77391d8b2ebef4a974ef32bf46ea');
await save('apps/web/public/brand/InterVariable.woff2', woff);
await save('apps/web/public/brand/INTER-LICENSE.txt', licence);
await save('apps/client/assets/brand/InterVariable.ttf', ttf);
await save('apps/client/assets/brand/INTER-LICENSE.txt', licence);

const symbolMaster = await readFile(resolve(root, tokens.logo.source));
if (gitBlob(symbolMaster) !== tokens.logo.sourceGitBlob) {
  throw new Error('Vector logo source changed: review and approve the master before regenerating');
}
const iconMaster = await readFile(resolve(root, tokens.appIcon.source));
if (gitBlob(iconMaster) !== tokens.appIcon.sourceGitBlob) {
  throw new Error('Vector app-icon source changed: review and approve the master before regenerating');
}

const primarySvg = colouriseCurrentColour(symbolMaster, tokens.colours.indigo);
const reverseSvg = colouriseCurrentColour(symbolMaster, tokens.colours.ivory);
await save('apps/web/public/brand/opfin-symbol.svg', primarySvg);
await save('apps/web/public/brand/opfin-symbol-reverse.svg', reverseSvg);

const mono = await sharp(primarySvg, { density: 384 }).resize(512, 512, { fit: 'contain' }).png().toBuffer();
const reverse = await sharp(reverseSvg, { density: 384 }).resize(512, 512, { fit: 'contain' }).png().toBuffer();
await save('apps/web/public/brand/opfin-symbol.png', mono);
await save('apps/web/public/brand/opfin-symbol-reverse.png', reverse);
await save('apps/client/assets/brand/opfin-symbol.png', mono);
await save('apps/client/assets/brand/opfin-symbol-reverse.png', reverse);

const icon = await sharp(iconMaster, { density: 384 }).resize(1024, 1024, { fit: 'fill' }).png().toBuffer();
await save('apps/client/assets/brand/opfin-app-icon.png', icon);
await save('apps/web/src/app/icon.png', await sharp(icon).resize(192, 192).png().toBuffer());

for (const [density, size] of Object.entries({ mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 })) {
  await save(
    `apps/client/android/app/src/main/res/mipmap-${density}/ic_launcher.png`,
    await sharp(icon).resize(size, size).png().toBuffer(),
  );
}

try {
  const contents = JSON.parse(
    await readFile(resolve(root, 'apps/client/ios/Runner/Assets.xcassets/AppIcon.appiconset/Contents.json'), 'utf8'),
  );
  for (const image of contents.images) {
    if (!image.filename || !image.size || !image.scale) continue;
    const size = Math.round(parseFloat(image.size) * parseFloat(image.scale));
    if (!Number.isFinite(size) || size < 16 || size > 1024 || image.filename.includes('/')) {
      throw new Error('Unexpected iOS icon specification');
    }
    await save(
      `apps/client/ios/Runner/Assets.xcassets/AppIcon.appiconset/${image.filename}`,
      await sharp(icon).resize(size, size).removeAlpha().png().toBuffer(),
    );
  }
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
  console.log('iOS icon catalogue is generated by the existing preparation tool; use assets/brand/opfin-app-icon.png.');
}

for (const path of [
  'brand/v3/assets/opfin-symbol-master.svg',
  'brand/v3/assets/opfin-app-icon-master.svg',
  'brand/v3/assets/opfin-lockup-horizontal.svg',
  'brand/v3/assets/opfin-lockup-stacked.svg',
  'brand/v3/assets/opfin-wordmark.svg',
  'brand/v3/assets/opfin-progress-path.svg',
  'brand/v3/assets/opfin-feature-graphic-master.svg',
]) {
  const data = await readFile(resolve(root, path));
  manifest.files[path] = digest(data);
}

await writeFile(resolve(root, 'brand/asset-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(JSON.stringify({
  brandSystemVersion: tokens.version,
  vectorMaster: tokens.logo.source,
  appIconMaster: tokens.appIcon.source,
  generatedAssets: Object.keys(manifest.files).length,
}));
